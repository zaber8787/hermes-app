#!/usr/bin/env python3
"""SESSIONDIR B3: publish-time local CJK fallback mirror (isolated dirs only).

    python3 web/test_release_fonts.py        # exit 0 = green

The engine's web-font-fallback table (relative gstatic woff2 paths compiled
into main.dart.js) must be mirrored into the release, with
window.flutterConfiguration.fontFallbackBaseUrl redirected at it — same
official lazy chunks, our origin, no fonts.gstatic.com dependency (report:
Chinese becomes tofu when gstatic is delayed; first card unaffected).
Red-on-old: scripts absent / release unpatched (cold trace fetched 7
fonts.gstatic.com files).
"""
import pathlib
import re
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parents[1]
DETAILS = []
BOOTSTRAP = """// generated by flutter
window._flutter = {};
_flutter.loader = new FlutterLoader();
_flutter.loader.load({
  serviceWorkerSettings: {
    serviceWorkerVersion: "12345"
  }
});
"""
TABLE = ('A.f("Noto Sans TC 0","notosanstc/v36/stemA.0.woff2"),'
         'A.f("Noto Sans TC 1","notosanstc/v36/stemA.1.woff2"),'
         'A.f("Noto Sans SC 37","notosanssc/v37/stemB.37.woff2")')


def check(condition, message):
    if not condition:
        raise AssertionError(message)
    DETAILS.append(message)


def woff2(tag):
    return b"wOF2" + tag.encode() + bytes(4096 - 4 - len(tag))


def make_release(src_dir):
    rel = pathlib.Path(tempfile.mkdtemp(prefix="release-cjk-"))
    (rel / "flutter_bootstrap.js").write_text(BOOTSTRAP)
    (rel / "index.html").write_text(
        "<html><head><title>h</title></head><body></body></html>")
    (rel / "assets").mkdir()
    (rel / "assets" / "FontManifest.json").write_text(
        '[{"family":"MaterialIcons","fonts":[{"asset":"fonts/MaterialIcons-Regular.otf"}]}]')
    (rel / "main.dart.js").write_text(
        "var x=0;" + TABLE + ";main();\n" + "x" * 200)
    return rel


def rel_read(rel):
    return (rel / "index.html").read_text()


def run(script, *args):
    return subprocess.run([sys.executable, str(REPO / "web" / script), *args],
                          capture_output=True, text=True)


def main():
    check((REPO / "web" / "make-cjk-mirror.py").is_file(),
          "web/make-cjk-mirror.py exists (red-on-old: missing)")
    check((REPO / "web" / "patch_release_fonts.py").is_file(),
          "web/patch_release_fonts.py exists (red-on-old: missing)")

    # offline fake gstatic over file://
    src = pathlib.Path(tempfile.mkdtemp(prefix="fake-gstatic-"))
    (src / "notosanstc" / "v36").mkdir(parents=True)
    (src / "notosanssc" / "v37").mkdir(parents=True)
    (src / "notosanstc" / "v36" / "stemA.0.woff2").write_bytes(woff2("tc0"))
    (src / "notosanstc" / "v36" / "stemA.1.woff2").write_bytes(woff2("tc1"))
    (src / "notosanssc" / "v37" / "stemB.37.woff2").write_bytes(woff2("sc37"))

    mirror = pathlib.Path(tempfile.mkdtemp(prefix="mirror-"))
    rel = make_release(src)
    r = run("make-cjk-mirror.py", "--main-js", str(rel / "main.dart.js"),
            "--mirror", str(mirror), "--base", f"file://{src}/")
    check(r.returncode == 0, f"mirror completes: {r.stdout}{r.stderr[-300:]}")
    check("table=3" in r.stdout and "absent=0" in r.stdout,
          f"all table entries mirrored: {r.stdout.strip()}")
    check((mirror / "notosanstc" / "v36" / "stemA.0.woff2").is_file()
          and (mirror / "notosanssc" / "v37" / "stemB.37.woff2").read_bytes()
          == (src / "notosanssc" / "v37" / "stemB.37.woff2").read_bytes(),
          "mirrored files keep the exact hosted bytes")

    r = run("patch_release_fonts.py", str(rel), "--mirror", str(mirror))
    check(r.returncode == 0, f"patch applied: {r.stdout}{r.stderr[-300:]}")
    boot = (rel / "flutter_bootstrap.js").read_text()
    check("fonts.gstatic.com/s/" in boot and "cjk-mirror/" in boot
          and "window.fetch" in boot,
          "fetch shim reroutes gstatic chunk URLs to the local mirror "
          "(red-on-old: engine ignores fontFallbackBaseUrl, fetched gstatic)")
    check(boot.count("window.fetch=function") == 1
          and boot.count("_flutter.loader.load({") == 1
          and 'serviceWorkerVersion: "12345"' in boot,
          "one shim injected, loader call intact")
    check((rel / "cjk-mirror" / "notosanstc" / "v36" / "stemA.1.woff2").read_bytes()
          == (src / "notosanstc" / "v36" / "stemA.1.woff2").read_bytes(),
          "release carries the mirrored chunks byte-identically")

    r = run("patch_release_fonts.py", str(rel), "--mirror", str(mirror))
    check(r.returncode == 0 and (rel / "flutter_bootstrap.js").read_text() == boot
          and "unchanged" in r.stdout, "rerunning the patch is a no-op")

    # B2-as-prioritization: the boot wave (declared fonts + main.dart.js)
    # must be PRELOADED from index.html so the manifest fetch at the end of
    # JS boot finds everything warm — the first frame stops waiting on the
    head = (rel / "index.html").read_text()
    check(head.count('rel="preload"') == 1 and 'main.dart.js' in head,
          "entry-script preload injected exactly once (red-on-old: none)")
    boot2 = (rel / "flutter_bootstrap.js").read_text()
    check("cjk-prefetch" in boot2 and "getEntriesByName" in boot2
          and "FontManifest.json" in boot2,
          "font prefetch gated on entry-script download completion")

    # incomplete source must NOT half-mirror into tofu
    src2 = pathlib.Path(tempfile.mkdtemp(prefix="fake-gstatic-partial-"))
    (src2 / "notosanstc" / "v36").mkdir(parents=True)
    (src2 / "notosanstc" / "v36" / "stemA.0.woff2").write_bytes(woff2("tc0"))
    mirror2 = pathlib.Path(tempfile.mkdtemp(prefix="mirror2-"))
    rel2 = make_release(src2)
    r = subprocess.run(
        [sys.executable, str(REPO / "web" / "patch_release_fonts.py"),
         str(rel2), "--mirror", str(mirror2), "--base", f"file://{src2}/"],
        capture_output=True, text=True)
    check(r.returncode != 0, "an incomplete mirror fails loudly, not silently")
    check("fontFallbackBaseUrl" not in (rel2 / "flutter_bootstrap.js").read_text(),
          "no redirect survives a failed mirror")
    check(not any((rel2 / "cjk-mirror").rglob("*.woff2")) if (rel2 / "cjk-mirror").is_dir() else True,
          "a failed patch leaves no half-populated mirror in the release")

    print(f"WEB-FONTS: PASS ({len(DETAILS)} assertions)")


if __name__ == "__main__":
    try:
        main()
    except AssertionError as exc:
        print(f"WEB-FONTS: FAIL: {exc}")
        sys.exit(1)
